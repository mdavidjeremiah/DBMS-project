const { chromium }=require(process.env.HW_PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8876/operations.html',{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'Available tasks'}).waitFor();
 await page.getByRole('button',{name:'Create requisition',exact:true}).click();
 await page.locator('.dialog [name=product]').selectOption({label:'Browser test cement'});
 await page.getByLabel('Quantity',{exact:true}).fill('2');
 await page.getByLabel('Unit cost (UGX)',{exact:true}).fill('100');
 await page.getByRole('button',{name:'Confirm and save',exact:true}).click();
 await page.getByText('Create requisition saved successfully.',{exact:true}).waitFor();
 const requisitions=await page.evaluate(async()=>await (await fetch('/api/purchase-requisitions')).json());
 if(!requisitions.length)throw new Error('Saved requisition missing');
 await page.screenshot({path:'.codex-review/operations-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.waitForFunction(()=>document.querySelector('#hw-sidebar').getBoundingClientRect().right<=0);
 await page.screenshot({path:'.codex-review/operations-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw new Error('Page overflows at mobile width');
 await page.getByRole('button',{name:'Set product prices',exact:true}).click();
 await page.locator('.dialog [name=product]').selectOption({label:'Browser test cement'});
 if(await page.getByLabel('Selling price (UGX)',{exact:true}).inputValue()!=='200.00')throw new Error('Price autofill failed');
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 if(errors.length)throw new Error(errors.join('; '));
 console.log('Browser PASS: requisition saved through UI/API/database; pricing autofill; desktop/mobile render; no page errors; no mobile overflow.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
